"""Single source of truth for the report figures: every plot is rebuilt from the committed CSVs.

Run (repo root):  python3 make_figures.py [--dir tests/unit/artifacts] [--out figures]
Inputs  (written by the tests / cost_accounting.py):
  label_budget_Z4Z5.csv, label_budget_Z3.csv            <- test_label_budget.py
  label_budget_cost_assumed_Z4Z5.csv                    <- cost_accounting.py
  label_noise_Z4.csv  (optional)                         <- test_readout_noise.py   (file stem comes from the burst name)
Outputs: fig_label_budget.png, fig_alias_vs_time.png, fig_label_noise.png (if input exists), numbers.md
"""
import argparse
import csv
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ap = argparse.ArgumentParser()
ap.add_argument("--dir", default="tests/unit/artifacts")
ap.add_argument("--out", default="figures")
a = ap.parse_args()
D, O = Path(a.dir), Path(a.out)
O.mkdir(exist_ok=True)
OPT = 5.708
rd = lambda name: list(csv.DictReader(open(D / name))) if (D / name).exists() else None
f = float
md = ["# Numbers behind the figures (generated by make_figures.py)\n"]

# 1. LER vs labeled shots
fig, ax = plt.subplots(figsize=(6, 4))
for burst, mk in (("Z4Z5", "o"), ("Z3", "s")):
    rows = rd(f"label_budget_{burst}.csv")
    if rows:
        ax.errorbar([int(r["N"]) for r in rows], [f(r["mean_ler"]) for r in rows], yerr=[f(r["ci95"]) for r in rows],
                    marker=mk, capsize=3, label=f"{burst} burst")
        md += [f"\n## {burst}: LER vs N\n", "| N | LER % | 95% CI | wrong alias |", "|---|---|---|---|"]
        md += [f"| {r['N']} | {f(r['mean_ler']):.2f} | {f(r['ci95']):.2f} | {f(r['frac_wrong_alias']):.0%} |" for r in rows]
ax.axhline(OPT, ls=":", color="black", label=f"Bayes optimum {OPT}%")
ax.set_xscale("symlog", linthresh=64); ax.set_xlabel("labeled shots N"); ax.set_ylabel("exact LER on RTL (%)")
ax.legend(fontsize=8); fig.tight_layout(); fig.savefig(O / "fig_label_budget.png", dpi=200); plt.close(fig)

# 2. wrong alias vs time share (Z4Z5), for the assumed shot-time cases
rows = rd("label_budget_cost_assumed_Z4Z5.csv")
if rows:
    fig, ax = plt.subplots(figsize=(6, 4))
    for key in [k for k in rows[0] if k.startswith("time_share_pct")]:
        ax.plot([f(r[key]) for r in rows], [100 * f(r["frac_wrong_alias"]) for r in rows], marker="o", label=key.split("[")[1][:-1] + "...")
    ax.set_xlabel("share of time spent on labeled shots (%)"); ax.set_ylabel("runs on the wrong alias (%)")
    ax.legend(fontsize=8, title="shot-time case"); fig.tight_layout(); fig.savefig(O / "fig_alias_vs_time.png", dpi=200); plt.close(fig)

# 3. label noise
rows = rd("label_noise_Z4Z5.csv")
if rows:
    n = max(int(r["N"]) for r in rows)
    sel = [r for r in rows if int(r["N"]) == n]
    fig, ax = plt.subplots(figsize=(6, 4))
    for tag in ("naive", "aware"):
        ax.errorbar([f(r["q"]) for r in sel], [f(r[f"{tag}_ler"]) for r in sel], yerr=[f(r[f"{tag}_ci95"]) for r in sel],
                    marker="o", capsize=3, label=f"{tag} fit")
    ax.axhline(OPT, ls=":", color="black"); ax.set_xlabel("label flip probability q"); ax.set_ylabel("exact LER on RTL (%)")
    ax.set_title(f"Z4Z5 burst, N={n}"); ax.legend(fontsize=8); fig.tight_layout()
    fig.savefig(O / "fig_label_noise.png", dpi=200); plt.close(fig)

(O / "numbers.md").write_text("\n".join(md) + "\n")
print("wrote:", sorted(p.name for p in O.iterdir()))
